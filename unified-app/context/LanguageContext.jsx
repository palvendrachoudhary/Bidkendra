    // Check exact match
    if (TRANSLATION_DICTIONARY[clean] && TRANSLATION_DICTIONARY[clean][currentLang]) {
      return TRANSLATION_DICTIONARY[clean][currentLang];
    }
    // Case-insensitive fallback
    const lower = clean.toLowerCase();
    for (const [key, trans] of Object.entries(TRANSLATION_DICTIONARY)) {
      if (key.toLowerCase() === lower && trans[currentLang]) {
        return trans[currentLang];
      }
    }
    return text;
